/* ---------- 索引 & 改造链 ---------- */
const ShipData = {};
SHIPS.forEach(s => ShipData[s.id] = s);

/* 生成改造链（kai -> kai2） */
function remodelChain(id) {
  const chain = [id];
  let cur = ShipData[id];
  if (cur.kai) { chain.push(cur.id + '_kai'); if (cur.kai2) chain.push(cur.id + '_kai2'); }
  return chain;
}

/* 可建造舰池（按配方筛选） */
function buildPool(recipe) {
  return SHIPS.filter(s => s.buildable !== false &&
    recipe.fuel >= s.build.fuel && recipe.ammo >= s.build.ammo &&
    recipe.steel >= s.build.steel && recipe.baux >= s.build.baux);
}

